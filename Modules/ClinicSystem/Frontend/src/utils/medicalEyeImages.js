/**
 * Helper function to get a random eye image from a category
 * @param {string} category - The category name (e.g., 'fundus', 'oct', 'anatomy')
 * @returns {string} Image URL
 */
export const getRandomImage = (category) => {
    const images = medicalEyeImages[category];
    if (!images) return medicalEyeImages.placeholders.noImage;
    
    const keys = Object.keys(images);
    const randomKey = keys[Math.floor(Math.random() * keys.length)];
    return images[randomKey];
};

/**
 * Get appropriate placeholder based on examination type
 * @param {string} type - Examination type
 * @returns {string} Placeholder image URL
 */
export const getPlaceholderByType = (type) => {
    const typeMap = {
        'fundus': medicalEyeImages.placeholders.fundusPlaceholder,
        'oct': medicalEyeImages.placeholders.octPlaceholder,
        'examination': medicalEyeImages.placeholders.eyeExamPlaceholder,
        'test': medicalEyeImages.placeholders.testResultPlaceholder,
    };
    
    return typeMap[type?.toLowerCase()] || medicalEyeImages.placeholders.noImage;
};

