// Helper function to get translation
export const getTranslation = (lang, section, key) => {
  try {
    return translations[section]?.[lang]?.[key] || translations.common[lang]?.[key] || key;
  } catch (e) {
    console.warn(`Translation not found for ${section}.${key}`);
    return key;
  }
};

